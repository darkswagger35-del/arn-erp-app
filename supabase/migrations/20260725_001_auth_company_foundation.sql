CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS public.companies (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    name text NOT NULL CHECK (length(trim(name)) > 0),
    legal_name text NULL,
    phone text NULL,
    email text NULL,
    tax_number text NULL,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.profiles (
    id uuid PRIMARY KEY,
    company_id uuid NOT NULL,
    full_name text NOT NULL CHECK (length(trim(full_name)) > 0),
    phone text NULL,
    role text NOT NULL CHECK (role IN ('admin', 'secretary', 'technician')),
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT profiles_company_fk
        FOREIGN KEY (company_id) REFERENCES public.companies(id) ON DELETE RESTRICT,
    CONSTRAINT profiles_auth_fk
        FOREIGN KEY (id) REFERENCES auth.users(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS public.company_settings (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    company_id uuid NOT NULL UNIQUE,
    currency_code text NOT NULL DEFAULT 'TRY',
    locale_code text NOT NULL DEFAULT 'tr-TR',
    timezone text NOT NULL DEFAULT 'Europe/Istanbul',
    maintenance_reminder_days integer NOT NULL DEFAULT 15 CHECK (maintenance_reminder_days >= 0),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT company_settings_company_fk
        FOREIGN KEY (company_id) REFERENCES public.companies(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS public.audit_logs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id uuid NOT NULL,
    user_id uuid NULL,
    action text NOT NULL,
    entity_type text NOT NULL,
    entity_id uuid NULL,
    old_values jsonb NULL,
    new_values jsonb NULL,
    metadata jsonb NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT audit_logs_company_fk
        FOREIGN KEY (company_id) REFERENCES public.companies(id) ON DELETE RESTRICT,
    CONSTRAINT audit_logs_user_fk
        FOREIGN KEY (user_id) REFERENCES auth.users(id) ON DELETE SET NULL
);

