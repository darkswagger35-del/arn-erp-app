CREATE OR REPLACE FUNCTION public.enforce_profile_update_policy()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  current_user_id uuid := auth.uid();
  current_role text;
  current_company_id uuid;
  self_update boolean;
BEGIN
  IF current_user_id IS NULL THEN
    RAISE EXCEPTION 'Authentication required for profile updates.' USING ERRCODE = '42501';
  END IF;

  SELECT role, company_id
    INTO current_role, current_company_id
    FROM public.profiles
    WHERE id = current_user_id AND is_active = true
    LIMIT 1;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'No active profile exists for the authenticated user.' USING ERRCODE = '42501';
  END IF;

  IF NEW.id IS DISTINCT FROM OLD.id OR NEW.company_id IS DISTINCT FROM OLD.company_id OR NEW.created_at IS DISTINCT FROM OLD.created_at THEN
    RAISE EXCEPTION 'Identity fields of a profile cannot be changed.' USING ERRCODE = '42501';
  END IF;

  self_update := (OLD.id = current_user_id);

  IF self_update THEN
    IF NEW.full_name IS NOT DISTINCT FROM OLD.full_name
       AND NEW.phone IS NOT DISTINCT FROM OLD.phone
       AND NEW.role IS NOT DISTINCT FROM OLD.role
       AND NEW.is_active IS NOT DISTINCT FROM OLD.is_active THEN
      RETURN NEW;
    END IF;

    IF NEW.role IS DISTINCT FROM OLD.role OR NEW.is_active IS DISTINCT FROM OLD.is_active THEN
      RAISE EXCEPTION 'You may only update your own full_name and phone.' USING ERRCODE = '42501';
    END IF;

    IF NEW.full_name IS DISTINCT FROM OLD.full_name OR NEW.phone IS DISTINCT FROM OLD.phone THEN
      RETURN NEW;
    END IF;

    RETURN NEW;
  END IF;

  IF current_role = 'admin' AND current_company_id = OLD.company_id THEN
    IF NEW.full_name IS NOT DISTINCT FROM OLD.full_name
       AND NEW.phone IS NOT DISTINCT FROM OLD.phone
       AND NEW.role IS NOT DISTINCT FROM OLD.role
       AND NEW.is_active IS NOT DISTINCT FROM OLD.is_active THEN
      RETURN NEW;
    END IF;

    IF NEW.full_name IS DISTINCT FROM OLD.full_name OR NEW.phone IS DISTINCT FROM OLD.phone OR NEW.role IS DISTINCT FROM OLD.role OR NEW.is_active IS DISTINCT FROM OLD.is_active THEN
      RETURN NEW;
    END IF;
  END IF;

  RAISE EXCEPTION 'You are not allowed to update this profile.' USING ERRCODE = '42501';
END;
$$;

