DROP POLICY IF EXISTS companies_select_own_company ON public.companies;
CREATE POLICY companies_select_own_company
ON public.companies
FOR SELECT
USING (
  is_active = true AND id = public.current_user_company_id()
);

-- Company activation is intentionally not client-editable here.
-- Activation and deactivation should be handled through a trusted server-side process.
DROP POLICY IF EXISTS companies_update_own_company ON public.companies;
CREATE POLICY companies_update_own_company
ON public.companies
FOR UPDATE
USING (
  public.is_admin() AND id = public.current_user_company_id()
)
WITH CHECK (
  public.is_admin() AND id = public.current_user_company_id() AND is_active = true
);

